test('map placement, move and zone save use the existing event backend', async ({ page }) => {
    await login(page, 'organizer@example.test');
    await page.goto('#/events/browser-flow/map');
    await expect(page.getByRole('button', { name: 'Place Orb', exact: true })).toBeEnabled();
    await page.getByRole('button', { name: 'Place Orb', exact: true }).click();
    const canvas = page.locator('.maplibregl-canvas');
    const box = await canvas.boundingBox();
    await canvas.click({ position: { x: box!.width / 2, y: box!.height / 2 } });
    await expect(page.getByRole('heading', { name: 'Orb properties' })).toBeVisible();
    await page.getByRole('button', { name: 'Save', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Selected Orb' })).toBeVisible();
    await page.getByRole('button', { name: 'Move', exact: true }).click();
    await canvas.click({ position: { x: box!.width / 2 + 25, y: box!.height / 2 } });
    await page.getByRole('button', { name: 'Save', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Selected Orb' })).toBeVisible();
    await page.getByRole('button', { name: 'Draw / edit zone', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Save zone', exact: true })).toBeEnabled();
    await page.getByRole('button', { name: 'Save zone', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Selected Orb' })).toBeVisible();
    await page.screenshot({ path: '/tmp/orbs-admin-map.png', fullPage: true });
});
